insert into public.hse_escalation_rules(name,priority,overdue_hours,escalation_level,target_role,active)
select x.name,x.priority,x.overdue_hours,x.escalation_level,x.target_role,true
from (
  values
    ('Critical immediate escalation','Critical',0,1,'manager'),
    ('Critical executive escalation','Critical',24,2,'admin'),
    ('High overdue escalation','High',24,1,'manager'),
    ('High executive escalation','High',72,2,'admin'),
    ('Medium overdue escalation','Medium',72,1,'manager'),
    ('Low overdue escalation','Low',168,1,'manager')
) as x(name,priority,overdue_hours,escalation_level,target_role)
where not exists (
  select 1 from public.hse_escalation_rules r
  where r.name=x.name
);

create or replace function private.evaluate_hse_action_escalations()
returns integer
language plpgsql
security definer
set search_path=''
as $$
declare
  inserted_count integer:=0;
begin
  with eligible as (
    select
      a.id as action_id,
      r.id as rule_id,
      r.escalation_level,
      r.target_role,
      'Action '||a.action_no||' is overdue by escalation rule: '||r.name as reason
    from public.hse_actions a
    join public.hse_escalation_rules r
      on r.active=true and r.priority=a.priority
    where a.status not in ('Completed','Closed','Cancelled')
      and a.due_at is not null
      and now() >= a.due_at + make_interval(hours=>r.overdue_hours)
      and not exists (
        select 1 from public.hse_action_escalations e
        where e.action_id=a.id and e.rule_id=r.id
      )
  ), inserted as (
    insert into public.hse_action_escalations(action_id,rule_id,escalation_level,target_role,reason)
    select action_id,rule_id,escalation_level,target_role,reason from eligible
    returning action_id,escalation_level
  )
  select count(*) into inserted_count from inserted;

  update public.hse_actions a
  set escalation_level=x.max_level,updated_at=now()
  from (
    select action_id,max(escalation_level) max_level
    from public.hse_action_escalations
    where status in ('Open','Acknowledged')
    group by action_id
  ) x
  where a.id=x.action_id and a.escalation_level is distinct from x.max_level;

  return inserted_count;
end;
$$;

revoke all on function private.evaluate_hse_action_escalations() from public,anon,authenticated;

do $$
declare existing_job bigint;
begin
  select jobid into existing_job from cron.job where jobname='hse_action_escalation_hourly' limit 1;
  if existing_job is not null then
    perform cron.unschedule(existing_job);
  end if;
  perform cron.schedule(
    'hse_action_escalation_hourly',
    '15 * * * *',
    'select private.evaluate_hse_action_escalations();'
  );
end $$;

